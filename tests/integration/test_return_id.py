ASYNC_URL = os.getenv(
    "TEST_POSTGRESQL_URL", "postgresql://postgres:mwtest@127.0.0.1:15432/mwtest"
)


@pytest.fixture
async def async_backend():
    from nexusql import PSYCOPG_AVAILABLE
    if not PSYCOPG_AVAILABLE:
        pytest.skip("psycopg not installed")
    from nexusql import AsyncPostgresBackend

    backend = AsyncPostgresBackend(ASYNC_URL, max_pool_size=4)
    try:
        await backend.connect()
    except Exception as exc:
        pytest.skip(f"PostgreSQL not reachable for async tests: {exc}")
    yield backend
    await backend.disconnect()


async def test_async_backend_return_id(async_backend):
    name = table_name()
    try:
        await async_backend.execute(
            f"CREATE TABLE {name} (id SERIAL PRIMARY KEY, name TEXT)"
        )
        first = await async_backend.execute(
            f"INSERT INTO {name} (name) VALUES (:name)", {"name": "a"}, return_id=True
        )
        second = await async_backend.execute_async(
            f"INSERT INTO {name} (name) VALUES (:name)", {"name": "b"}, return_id=True
        )
        assert first == 1 and second == 2

        explicit = await async_backend.execute(
            f"INSERT INTO {name} (name) VALUES (:name) RETURNING name",
            {"name": "c"}, return_id=True,
        )
        assert explicit == "c"

        async with async_backend.transaction():
            third = await async_backend.execute(
                f"INSERT INTO {name} (name) VALUES (:name)", {"name": "d"},
                return_id=True,
            )
        assert third == 4

        with pytest.raises(ValueError, match="only applies to INSERT"):
            await async_backend.execute(f"DELETE FROM {name}", return_id=True)

        rows = await async_backend.execute(f"SELECT id FROM {name} ORDER BY id")
        assert [r["id"] for r in rows] == [1, 2, 3, 4]
    finally:
        await async_backend.execute(f"DROP TABLE IF EXISTS {name}")


async def test_async_backend_named_params_are_converted(async_backend):
    """The async path reads :name like the sync manager; this used to be
    passed to psycopg untouched and fail with a syntax error."""
    rows = await async_backend.execute(
        "SELECT :a AS a, :a_b AS ab, 'x'::text AS cast", {"a": 1, "a_b": 2}
    )
    assert rows == [{"a": 1, "ab": 2, "cast": "x"}]
