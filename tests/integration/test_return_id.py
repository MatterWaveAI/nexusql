"""
execute(..., return_id=True) against live backends.

The canonical schema uses SERIAL PRIMARY KEY, which the translator turns
into each backend's auto-increment column, so the same INSERT must hand back
the generated key on SQLite, PostgreSQL, MySQL and SQL Server. Backends that
are not reachable are skipped at collection (see conftest).
"""

import os
import uuid

import pytest

from nexusql import DatabaseManager

BACKENDS = ["sqlite", "postgresql", "mysql", "mssql"]


def table_name() -> str:
    return "rid_" + uuid.uuid4().hex[:10]


@pytest.fixture
def table(db_manager):
    name = table_name()
    db_manager.execute(
        f"CREATE TABLE {name} (id SERIAL PRIMARY KEY, name VARCHAR(50) NOT NULL)"
    )
    yield name
    try:
        db_manager.execute(f"DROP TABLE {name}")
    except Exception:
        pass


@pytest.mark.parametrize("db_manager", BACKENDS, indirect=True)
class TestReturnId:
    def test_generated_key_comes_back(self, db_manager, table):
        first = db_manager.execute(
            f"INSERT INTO {table} (name) VALUES (:name)", {"name": "one"}, return_id=True
        )
        second = db_manager.execute(
            f"INSERT INTO {table} (name) VALUES (:name)", {"name": "two"}, return_id=True
        )
        assert isinstance(first, int) and isinstance(second, int)
        assert second > first
        row = db_manager.fetch_one(
            f"SELECT name FROM {table} WHERE id = :id", {"id": second}
        )
        assert row == {"name": "two"}

    def test_write_is_durable(self, db_manager, table):
        new_id = db_manager.execute(
            f"INSERT INTO {table} (name) VALUES (:name)", {"name": "kept"}, return_id=True
        )
        reader = DatabaseManager(db_manager.database_url)
        assert reader.connect()
        try:
            rows = reader.execute(f"SELECT id, name FROM {table}")
        finally:
            reader.disconnect()
        assert rows == [{"id": new_id, "name": "kept"}]

    def test_inside_transaction(self, db_manager, table):
        with db_manager.transaction():
            a = db_manager.execute(
                f"INSERT INTO {table} (name) VALUES (:name)", {"name": "a"}, return_id=True
            )
            b = db_manager.execute(
                f"INSERT INTO {table} (name) VALUES (:name)", {"name": "b"}, return_id=True
            )
        assert b > a
        rows = db_manager.execute(f"SELECT id FROM {table} ORDER BY id")
        assert [r["id"] for r in rows] == [a, b]

    def test_rolled_back_insert_leaves_connection_usable(self, db_manager, table):
        with pytest.raises(Exception):
            db_manager.execute(
                f"INSERT INTO {table} (name) VALUES (:name)", {"name": None},
                return_id=True,
            )
        new_id = db_manager.execute(
            f"INSERT INTO {table} (name) VALUES (:name)", {"name": "after"},
            return_id=True,
        )
        assert isinstance(new_id, int)


def test_postgres_composite_key_is_rejected(postgresql_url, skip_if_no_postgresql):
    db = DatabaseManager(postgresql_url)
    assert db.connect()
    name = table_name()
    try:
        db.execute(f"CREATE TABLE {name} (a INT, b INT, PRIMARY KEY (a, b))")
        with pytest.raises(ValueError, match="composite"):
            db.execute(
                f"INSERT INTO {name} (a, b) VALUES (:a, :b)", {"a": 1, "b": 2},
                return_id=True,
            )
        # The failed call must not have poisoned the connection.
        assert db.fetch_one("SELECT 1 AS ok") == {"ok": 1}
    finally:
        db.execute(f"DROP TABLE IF EXISTS {name}")
        db.disconnect()


def test_postgres_non_serial_primary_key(postgresql_url, skip_if_no_postgresql):
    """A UUID key generated by a default is still 'the generated ID'."""
    db = DatabaseManager(postgresql_url)
    assert db.connect()
    name = table_name()
    try:
        db.execute(
            f"CREATE TABLE {name} (id UUID PRIMARY KEY DEFAULT gen_random_uuid(), "
            "name TEXT)"
        )
        new_id = db.execute(
            f"INSERT INTO {name} (name) VALUES (:name)", {"name": "u"}, return_id=True
        )
        assert isinstance(new_id, uuid.UUID)
        assert db.fetch_one(f"SELECT name FROM {name} WHERE id = :id", {"id": new_id}) == {
            "name": "u"
        }
    finally:
        db.execute(f"DROP TABLE IF EXISTS {name}")
        db.disconnect()


def test_postgres_on_conflict_do_nothing_returns_none(postgresql_url, skip_if_no_postgresql):
    db = DatabaseManager(postgresql_url)
    assert db.connect()
    name = table_name()
    try:
        db.execute(f"CREATE TABLE {name} (id SERIAL PRIMARY KEY, name TEXT UNIQUE)")
        sql = f"INSERT INTO {name} (name) VALUES (:name) ON CONFLICT (name) DO NOTHING"
        assert db.execute(sql, {"name": "n"}, return_id=True) == 1
        assert db.execute(sql, {"name": "n"}, return_id=True) is None
    finally:
        db.execute(f"DROP TABLE IF EXISTS {name}")
        db.disconnect()


